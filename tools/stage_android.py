#!/usr/bin/env python3
"""Stage the nxnative host, the Biko3 runtime and the guest image for Android.

Inputs:
  * a pinned nxnative source tree (default: work/android/upstream/nxnative)
  * the patched guest image and its rewriter metadata (default: work/android/guest)
    produced from the public Biko3-development.ipa by tools/extract_ios_guest.py

Output (default: work/android/staged):
  host/            upstream dm/host copied, patched for Android, plus the Biko3
                   runtime sources (Biko3FS/Libnx/Input/Vulkan/Hooks)
  gen/             game_profile.h and Biko3HookTable.h
  assets/guest/    main.patched.bin and the .tsv metadata the loader reads
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILE = "000000000000B103"

GAME_PROFILE = """#pragma once
/* Synthetic Biko3 host profile; mirrors ios/profile/game.tsv. */
#define DM_GAME_TITLE_ID 0x000000000000B103ull
#define DM_GAME_PROGRAM_ID 0x000000000000B103ull
#define DM_GAME_NAME "Biko3"
#define DM_GAME_MODULES {"main"}
#define DM_GAME_NMOD 1
#define DM_GAME_ROMFS_MARKER "Data/bk3_00.pp"
#define DM_GAME_MEM_RESERVE 0x100000000ull
#define DM_GAME_MEM_ALIAS 0x10000000ull
#define DM_GAME_MEM_STACK 0x10000000ull
#define DM_GAME_APP_POOL 0xCD500000ull
#define DM_GAME_MEM_USED 0x4000000ull
#define DM_GAME_MEM_MAP_LIMIT 0
#define DM_GAME_SYS_RESOURCE 0x2000000ull
#define DM_GAME_GAME_ARGS ""
#define DM_GAME_ARGS ""
#define DM_GAME_OPMODE 0
#define DM_GAME_FPS_TARGET 0
#define DM_GAME_PAD_FULL 1
#define DM_GAME_PERF_BOOST 0
#define DM_GAME_CORE_PREEMPT 0
#define DM_GAME_DISPLAY_VERSIONS 0
#define DM_GAME_ENV ""
#define DM_GAME_SHARED_FONT_TTF 0
#define DM_GAME_ALLOC_BIG_ALIGN 0
"""

HID_ADAPTER = '''
/* Biko3 adapter: sample the real virtual/physical controller merge and latches. */
void biko3_read_native_pad(uint64_t *buttons, int32_t axes[4]) {
    NpadState state;
    uint32_t id = connected_id();
    fill(&state, id, style_of(id));
    *buttons = state.buttons;
    axes[0] = state.lx; axes[1] = state.ly;
    axes[2] = state.rx; axes[3] = state.ry;
}
'''

RUNTIME_SOURCES = ("Biko3FS.c", "Biko3Libnx.c", "Biko3Input.c", "Biko3Vulkan.c", "Biko3Hooks.c",
                   "Biko3GameProbe.c")
RUNTIME_HEADERS = ("Biko3FS.h", "Biko3Libnx.h", "Biko3Vulkan.h", "Biko3Audio.h", "Biko3VulkanExports.inc",
                   "Biko3GameProbe.h")
GUEST_FILES = ("main.patched.bin", "main.fixups.tsv", "main.gates.tsv")


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def hook_bindings(root: Path) -> list[dict]:
    hooks = []
    for name in ("vulkan-hooks.json", "libnx-hooks.json"):
        spec = json.loads((root / "ios/runtime" / name).read_text(encoding="utf8"))
        hooks.extend(spec["hooks"])
    slots = [hook["slot"] for hook in hooks]
    if len(slots) != len(set(slots)):
        raise ValueError("duplicate hook slots in the manifests")
    return hooks


def binding_header(hooks: list[dict], image: bytes, table_offset: int, table_size: int) -> str:
    if image[0x10:0x14] != b"NRO0":
        raise ValueError("guest image does not carry the NRO header")
    build = image[0x40:0x60]
    rows = "".join(
        '    {"%s", %d},\n' % (hook["symbol"], hook["slot"]) for hook in hooks
    )
    return (
        "/* Generated by tools/stage_android.py from the reviewed hook manifests. */\n"
        "#pragma once\n"
        "typedef struct { const char *symbol; unsigned slot; } Biko3HookBinding;\n"
        f"#define BIKO3_TABLE_OFFSET {table_offset:#x}u\n"
        f"#define BIKO3_TABLE_SIZE {table_size:#x}u\n"
        f"#define BIKO3_HOOK_COUNT {len(hooks)}u\n"
        "#define BIKO3_GAME_PROBE_ORIGINAL_OFFSET 0u  /* research hook disabled on Android */\n"
        f"static const unsigned char biko3_expected_build[32] = "
        "{" + ",".join(f"0x{byte:02x}" for byte in build) + "};\n"
        "static const Biko3HookBinding biko3_hook_bindings[] = {\n" + rows + "};\n"
    )


def read_fixups(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text(encoding="utf8").splitlines():
        if not line.startswith("# "):
            continue
        key, _, value = line[2:].partition("\t")
        values[key.strip()] = value.strip()
    return values


def stage(args) -> dict:
    root = ROOT
    upstream = args.nxnative_root.resolve()
    guest = args.guest_dir.resolve()
    out = args.out.resolve()
    if not (upstream / "dm/host/main.c").is_file():
        raise ValueError("nxnative source tree is missing dm/host/main.c")
    for name in GUEST_FILES:
        if not (guest / name).is_file():
            raise ValueError(f"guest directory is missing {name}")
    if out.exists():
        shutil.rmtree(out)
    host = out / "host"
    gen = out / "gen"
    assets = out / "assets/guest"
    host.mkdir(parents=True)
    gen.mkdir()
    assets.mkdir(parents=True)

    shutil.copytree(upstream / "dm/host", host, dirs_exist_ok=True)
    subprocess.run([sys.executable, str(root / "tools/patch_android_host.py"), "--host", str(host)], check=True)

    sys.path.insert(0, str(root / "tools"))
    from patch_libnx_host import patch_main
    from patch_android_guest_image import patch as patch_image

    main_c = host / "main.c"
    main_c.write_bytes(patch_main(main_c.read_bytes()))

    hid = host / "hle_hid.c"
    hid.write_text(hid.read_text(encoding="utf8") + HID_ADAPTER, encoding="utf8")

    image = (guest / "main.patched.bin").read_bytes()
    fixups = read_fixups(guest / "main.fixups.tsv")
    table_offset = 0xFAC000
    table_size = 0x4000
    if int(fixups["PATCH_OFF"], 16) - table_offset != table_size:
        raise ValueError("fixups header does not place the hook table before the patch area")

    (gen / "game_profile.h").write_text(GAME_PROFILE, encoding="utf8")
    hooks = hook_bindings(root)
    (gen / "Biko3HookTable.h").write_text(
        binding_header(hooks, image, table_offset, table_size), encoding="utf8"
    )

    for name in RUNTIME_SOURCES:
        shutil.copyfile(root / "ios/runtime" / name, host / name)
    for name in RUNTIME_HEADERS:
        shutil.copyfile(root / "ios/runtime" / name, host / name)
    audio = root / "android/port/src/Biko3AudioAndroid.c"
    if audio.is_file():
        shutil.copyfile(audio, host / "Biko3Audio.c")

    image_android, image_report = patch_image(image)
    (assets / "main.patched.bin").write_bytes(image_android)
    manifest_src = guest / "Biko3Data.manifest.json"
    if manifest_src.is_file():
        shutil.copyfile(manifest_src, assets / "Biko3Data.manifest.json")
    for name in GUEST_FILES:
        if name != "main.patched.bin":
            shutil.copyfile(guest / name, assets / name)
    for extra in ("main.sites.tsv", "main.cuts.tsv", "main.obs.tsv"):
        if (guest / extra).is_file():
            shutil.copyfile(guest / extra, assets / extra)

    report = {
        "profile": PROFILE,
        "guest_sha256": sha(guest / "main.patched.bin"),
        "guest_android_sha256": sha(assets / "main.patched.bin"),
        "guest_android_rewrite": image_report,
        "guest_bytes": len(image),
        "build_id": image[0x40:0x60].hex(),
        "hook_count": len(hooks),
        "table_offset": table_offset,
        "table_size": table_size,
        "nxnative": str(upstream),
        "host": str(host),
    }
    (out / "stage-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf8")
    print(json.dumps(report, indent=2))
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nxnative-root", type=Path, default=ROOT / "work/android/upstream/nxnative")
    parser.add_argument("--guest-dir", type=Path, default=ROOT / "work/android/guest")
    parser.add_argument("--out", type=Path, default=ROOT / "work/android/staged")
    stage(parser.parse_args(argv))


if __name__ == "__main__":
    main()
